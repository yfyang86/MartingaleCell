export const CL_SYMBOL_MAP: Map<string, ClSymbol> = new Map(
  CL_SYMBOLS.map((s) => [s.name.toUpperCase(), s]),
)

export function lookupSymbol(name: string): ClSymbol | undefined {
  const bare = name.split(':').pop() ?? name
  return CL_SYMBOL_MAP.get(bare.toUpperCase())
}
