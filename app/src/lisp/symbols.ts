/* Curated Common Lisp core symbol index — drives autocomplete, doc popovers
 * and signature help. name is lowercase; kind: fn | macro | var | class | const.
 */

export interface ClSymbol {
  name: string
  kind: 'fn' | 'macro' | 'var' | 'class' | 'const'
  arglist: string
  doc: string
}

const F = (name: string, arglist: string, doc: string): ClSymbol => ({ name, kind: 'fn', arglist, doc })
const M = (name: string, arglist: string, doc: string): ClSymbol => ({ name, kind: 'macro', arglist, doc })
const V = (name: string, doc: string): ClSymbol => ({ name, kind: 'var', arglist: '', doc })
const K = (name: string, doc: string): ClSymbol => ({ name, kind: 'class', arglist: '', doc })

